// MARXY-19: measures ragged-right paragraph setting quality for justif/core and tex-linebreak2 over
// the whole fixture corpus and writes the tables in packages/typeset/RESEARCH.md. A study harness,
// not product code: nothing here is imported by packages/typeset/src.
//
//   node packages/typeset/scripts/measure-rag.mjs            # print the tables
//   node packages/typeset/scripts/measure-rag.mjs --write     # refresh RESEARCH.md
//   node packages/typeset/scripts/measure-rag.mjs --verify    # fail if RESEARCH.md is stale
//   node packages/typeset/scripts/measure-rag.mjs --selftest  # check the metric arithmetic
