// Regenerates packages/core/src/highlight/languages.generated.ts (the language table: names only) and
// grammar-loaders.generated.ts (the lazy imports of each grammar) from shiki-languages.json. They are two files so that
// code that only needs to know which languages have a grammar never reaches the loaders, and so the grammars' chunks.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const allowlist = JSON.parse(readFileSync(join(root, 'scripts/allowlists/shiki-languages.json'), 'utf8'));
const dir = join(root, 'packages/core/src/highlight');

const grammarOf = Object.fromEntries(allowlist.languages.map(({ id, grammar }) => [id, grammar]));
const aliases = Object.entries(allowlist.aliases ?? {}).map(([id, target]) => {
  if (!grammarOf[target]) throw new Error(`alias ${id} → ${target}: not an allow-listed id`);
  return { id, grammar: grammarOf[target] };
});
const entries = [...allowlist.languages.map(({ id, grammar }) => ({ id, grammar })), ...aliases];
const uniqueGrammars = [...new Set(entries.map((e) => e.grammar))].sort();

const table = [
  '// Generated by scripts/generate-highlight-languages.mjs — do not edit.',
  '',
  '/** Markdown `language-*` id → Shiki grammar module id (allow-list only). */',
  `export const LANGUAGE_TO_GRAMMAR: Readonly<Record<string, string>> = {`,
  ...entries.map((e) => `  ${JSON.stringify(e.id)}: ${JSON.stringify(e.grammar)},`),
  '};',
  '',
];

const loaders = [
  '// Generated by scripts/generate-highlight-languages.mjs — do not edit.',
  '',
  '/** Lazy grammar loaders keyed by grammar id; each import is a separate chunk. */',
  'export const GRAMMAR_LOADERS: Readonly<Record<string, () => Promise<{ default: unknown }>>> = {',
  ...uniqueGrammars.map((g) => `  ${JSON.stringify(g)}: () => import('@shikijs/langs/${g}'),`),
  '};',
  '',
];

writeFileSync(join(dir, 'languages.generated.ts'), table.join('\n'));
writeFileSync(join(dir, 'grammar-loaders.generated.ts'), loaders.join('\n'));
console.log(`wrote ${dir} languages.generated.ts and grammar-loaders.generated.ts (${entries.length} language ids, ${uniqueGrammars.length} grammars)`);
