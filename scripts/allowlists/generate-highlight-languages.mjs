// Regenerates packages/core/src/highlight/languages.generated.ts from shiki-languages.json (MARXY-27).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const allowlist = JSON.parse(readFileSync(join(root, 'scripts/allowlists/shiki-languages.json'), 'utf8'));
const out = join(root, 'packages/core/src/highlight/languages.generated.ts');

const entries = allowlist.languages.map(({ id, grammar }) => ({ id, grammar }));
const uniqueGrammars = [...new Set(entries.map((e) => e.grammar))].sort();

const lines = [
  '// Generated by scripts/allowlists/generate-highlight-languages.mjs — do not edit.',
  '',
  '/** Markdown `language-*` id → Shiki grammar module id (allow-list only). */',
  `export const LANGUAGE_TO_GRAMMAR: Readonly<Record<string, string>> = {`,
  ...entries.map((e) => `  ${JSON.stringify(e.id)}: ${JSON.stringify(e.grammar)},`),
  '};',
  '',
  '/** Lazy grammar loaders keyed by grammar id; each import is a separate chunk. */',
  'export const GRAMMAR_LOADERS: Readonly<Record<string, () => Promise<{ default: unknown }>>> = {',
  ...uniqueGrammars.map((g) => `  ${JSON.stringify(g)}: () => import('@shikijs/langs/${g}'),`),
  '};',
  '',
];

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out} (${entries.length} language ids, ${uniqueGrammars.length} grammars)`);
