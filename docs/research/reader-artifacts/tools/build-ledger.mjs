// Builds 11-sources.md, the handbook's source ledger, from the sources arrays in data/NN.json, so the
// ledger and the chapters' footnotes cannot drift apart. Sources are merged by URL across chapters;
// the merged entry keeps the strictest (lowest) grade, the shallowest depth, and every chapter that
// cites it. Hand-written notes about weak and unverifiable sources live in data/ledger-notes.md and
// are appended verbatim. Run from the repository root:
//
//   node docs/research/reader-artifacts/tools/build-ledger.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'data');
const GRADE_ORDER = ['A', 'B', 'C', 'D', 'X', ''];
const DEPTH_ORDER = ['read in full', 'source', 'docs page', 'abstract only', 'search summary'];
const TIER = { 1: 'Tier 1, primary', 2: 'Tier 2, recognised expertise', 3: 'Tier 3, reputable secondary' };
const TITLES = {
  '01': 'Reading tasks', '02': 'Agent artifacts', '03': 'Structured output', '04': 'Code as read',
  '05': 'Diffs and provenance', '06': 'READMEs', '07': 'Trust and safety', '08': 'Teardown', '09': 'Colour and access',
};

const merged = new Map();
for (const f of readdirSync(dataDir).filter((n) => /^\d\d\.json$/.test(n)).sort()) {
  const nn = f.slice(0, 2);
  const data = JSON.parse(readFileSync(join(dataDir, f), 'utf8'));
  for (const s of data.sources ?? []) {
    // Files inside this repository are not external evidence; the chapters link them directly.
    if (!/^https?:\/\//.test(s.url ?? '')) continue;
    if (!/^[ABCDX]$/.test(s.grade ?? '')) s.grade = '';
    const key = (s.url ?? s.id).replace(/[#?].*$/, '').replace(/\/$/, '').toLowerCase();
    const prev = merged.get(key);
    if (!prev) {
      merged.set(key, { ...s, chapters: [nn] });
      continue;
    }
    if (!prev.chapters.includes(nn)) prev.chapters.push(nn);
    if (GRADE_ORDER.indexOf(s.grade ?? '') > GRADE_ORDER.indexOf(prev.grade ?? '') && s.grade) prev.grade = s.grade;
    if (DEPTH_ORDER.indexOf(s.depth ?? '') > DEPTH_ORDER.indexOf(prev.depth ?? '')) prev.depth = s.depth;
    if ((s.doesNotShow ?? '').length > (prev.doesNotShow ?? '').length) prev.doesNotShow = s.doesNotShow;
    if ((s.shows ?? '').length > (prev.shows ?? '').length) prev.shows = s.shows;
  }
}

const byTier = new Map();
for (const s of merged.values()) {
  const t = s.tier ?? 3;
  if (!byTier.has(t)) byTier.set(t, []);
  byTier.get(t).push(s);
}

const lines = [];
lines.push('<!-- Generated by tools/build-ledger.mjs from data/NN.json; edit the sidecars, then run the script. -->', '');
lines.push('# Source Ledger', '');
lines.push(
  '*Every source the handbook relies on, merged across chapters and graded, with what each shows and what it does not. The ledger comes from the chapters\' own source records, so a source cited in a chapter is here and a source here is cited in a chapter. Every entry was fetched in September 2026 and carries its access date and how much of it was read. None is cited from memory.*',
  '',
);
lines.push(
  'Evidence grades: **[A]** replicated findings or a meta-analysis · **[B]** one well-designed study · **[C]** small, limited or mixed studies · **[D]** expert convention, or convergence of shipping tools, without a direct test · **[X]** contested or contradicted. Part of the [Reader Artifacts Handbook](README.md).',
  '',
);
lines.push('## How sources were chosen and graded', '');
lines.push(
  'Sources fall into three tiers. **Tier 1** is primary: the paper (or its abstract on the publisher\'s page when the paper could not be read), the specification, the tool\'s own documentation, changelog or source, a project\'s LICENSE file. **Tier 2** is recognised expertise, including practitioner research such as Nielsen Norman Group\'s, labelled as such. **Tier 3** is reputable secondary sources, used sparingly. Wikipedia, listicles, AI-generated summaries and vendor claims presented as evidence were excluded.',
  '',
  'The grade on an entry is the grade of the strongest claim the chapters rest on it, capped by how much of it was read: an abstract-only study is not cited above **[C]** for a finding the abstract does not state. The entry says what the source does *not* show, because a source\'s reputation is often larger than its findings. **Depth** records what was read: *read in full*, *source* (code read), *docs page*, *abstract only*, or *search summary* (the page itself was not opened).',
  '',
);
const total = merged.size;
lines.push(`The ledger holds ${total} sources.`, '');

for (const t of [1, 2, 3]) {
  const list = byTier.get(t);
  if (!list?.length) continue;
  lines.push(`## ${TIER[t]}`, '');
  list.sort((a, b) => a.citation.localeCompare(b.citation));
  for (const s of list) {
    const cited = s.chapters.map((c) => `[${Number(c)}](${c}-${chapterSlug(c)}.md)`).join(', ');
    const grade = s.grade ? ` **[${s.grade}]**` : '';
    lines.push(`**${s.citation}**${grade}. ${s.depth ?? 'depth not recorded'}. Cited in chapter ${cited}.`);
    lines.push(`: ${s.shows ?? ''} ${s.doesNotShow ? `Does not show: ${lcfirst(s.doesNotShow)}` : ''}`.trim());
    lines.push(`  <${s.url}>. Accessed ${s.accessed}.`, '');
  }
}

const notes = join(dataDir, 'ledger-notes.md');
if (existsSync(notes)) lines.push(readFileSync(notes, 'utf8').trimEnd(), '');

writeFileSync(join(root, '11-sources.md'), lines.join('\n'));
console.log(`wrote 11-sources.md: ${total} sources`);

function chapterSlug(nn) {
  const files = readdirSync(root).filter((n) => n.startsWith(nn + '-') && n.endsWith('.md'));
  return files[0]?.slice(3, -3) ?? '';
}
function lcfirst(s) {
  return s ? s[0].toLowerCase() + s.slice(1) : s;
}
